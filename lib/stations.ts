// ── クイズ用ヘルパー ─────────────────────────────────────────────────────────

export interface Station {
  name: string;
  kana: string;
  number: number; // 1 始まり
}

export function stationAt(line: Line, index: number): Station {
  const [name, kana] = line.stations[index].split('|');
  return { name, kana, number: index + 1 };
}

/** 'JY' + 1 → 'JY01' */
export function stationCode(line: Line, number: number): string {
  return `${line.code}${String(number).padStart(2, '0')}`;
}

export interface StationQuestion {
  line: Line;
  answer: Station;
  choices: Station[]; // 正解を含む（シャッフル済み）
  prev: Station | null;
  next: Station | null;
}

function shuffle<T>(arr: T[]): T[] {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/**
 * 出題する lines から重複なしで count 問つくる。
 * 選択肢は同じ路線の駅から選ぶ。near のときは番号の近い駅を混ぜて当てずっぽうで当たりにくくし、
 * そうでなければ路線全体から選ぶ（ろせんずモードのふつう：だいたいの位置で見当をつけられる）。
 */
export function buildQuestions(lines: Line[], count: number, choiceCount = 4, near = true): StationQuestion[] {
  const pool = shuffle(lines.flatMap((line) => line.stations.map((_, i) => ({ line, i }))));
  return pool.slice(0, count).map(({ line, i }) => {
    const answer = stationAt(line, i);
    const others = line.stations
      .map((_, j) => ({ j, key: near ? Math.abs(j - i) + Math.random() * 4 : Math.random() }))
      .filter(({ j }) => j !== i)
      .sort((a, b) => a.key - b.key);
    const choices = shuffle([answer, ...others.slice(0, choiceCount - 1).map(({ j }) => stationAt(line, j))]);
    return {
      line,
      answer,
      choices,
      prev: i > 0 ? stationAt(line, i - 1) : null,
      next: i < line.stations.length - 1 ? stationAt(line, i + 1) : null,
    };
  });
}
