/**
 * 駅ナンバリングのデータ（えきめいクイズ用）。
 *
 * stations は番号順。index 0 が `${code}01`。
 * 「名前|よみ」の形で書く。番号は配列の位置から決まるので、駅を足すときは順番を崩さないこと。
 * 支線（丸ノ内線 方南町支線、西武の豊島線・西武有楽町線）は入れていない。
 * 番号は公式の駅ナンバリングに合わせる（山手線は JY01 東京 → JY02 神田 の向き、大江戸線は E01 新宿西口 … E28 都庁前）。
 * 西武池袋線は正式区間の 池袋〜吾野（SI01〜SI31）まで。
 */

